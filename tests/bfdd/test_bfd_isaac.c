static void test_reference(void)
{
	static const uint8_t zero[BFD_ISAAC_SEED_LEN];
	struct bfd_isaac ctx;
	unsigned int page;

	bfd_isaac_init(&ctx, zero);
	for (page = 0; page < 2; page++) {
		bfd_isaac_next_page(&ctx);
		assert(memcmp(ctx.rsl, randvect + page * BFD_ISAAC_PAGE, sizeof(ctx.rsl)) == 0);
	}
	printf("reference vectors: ok\n");
}

static void seed(struct bfd_isaac *ctx, uint32_t seed_val, uint32_t your_discr, const char *key)
{
	assert(bfd_isaac_seed(ctx, seed_val, your_discr, (const uint8_t *)key, strlen(key)));
}

/* RFC 9986 Section 10, Tables 1 and 2. */
static void test_rfc9986(void)
{
	static const uint32_t expected[] = {
		0x9af65d83, 0x44355d56, 0x9334074e, 0xb643ef59,
		0x74d659f1, 0x8966dc56, 0xa1f6f9bc, 0x21895a46,
	};
	struct bfd_isaac ctx;

	seed(&ctx, 0x0bfd5eed, 0x4002d15c, "RFC5880June");
	assert(memcmp(ctx.rsl, expected, sizeof(expected)) == 0);

	/* Your Discriminator is part of the seed, not only the Seed field. */
	seed(&ctx, 0x0bfd5eed, 0x4002d15d, "RFC5880June");
	assert(ctx.rsl[0] == 0xab350fb4);
	printf("RFC 9986 vectors: ok\n");
}

/*
 * The RFC's key makes 51 copies of a 20 byte record with 4 bytes left
 * over. Other lengths lay the seed buffer out differently.
 */
static void test_key_lengths(void)
{
	uint8_t longkey[BFD_ISAAC_KEY_MAX + 1];
	struct bfd_isaac ctx;
	size_t i;

	/* 16 byte records: 64 copies and nothing left over. Then two flips. */
	seed(&ctx, 0x11223344, 0xa1b2c3d4, "sevenby");
	assert(ctx.rsl[0] == 0x7a8c9a88 && ctx.rsl[1] == 0x81cd2e82);
	assert(ctx.rsl[2] == 0x717ef5dd && ctx.rsl[3] == 0x78bccab1);
	assert(ctx.rsl[255] == 0x54f80960);
	bfd_isaac_next_page(&ctx);
	assert(ctx.rsl[0] == 0x81509f2d);
	bfd_isaac_next_page(&ctx);
	assert(ctx.rsl[255] == 0x6db14bc8);

	/* The longest keyed MD5 key: 40 copies and most of another. */
	seed(&ctx, 0xffffffff, 1, "sixteenbyteskey1");
	assert(ctx.rsl[0] == 0xe7aa0410 && ctx.rsl[1] == 0x665ac62c);
	assert(ctx.rsl[2] == 0x61fbbf7b && ctx.rsl[3] == 0x8beb8454);

	/* One byte: the counter reaches 101. */
	seed(&ctx, 0x0bfd5eed, 0x4002d15c, "k");
	assert(ctx.rsl[0] == 0xbe612a51 && ctx.rsl[1] == 0xec720e46);

	/* The longest that fits: a single copy fills the buffer. */
	for (i = 0; i < sizeof(longkey); i++)
		longkey[i] = i * 7 + 3;
	assert(bfd_isaac_seed(&ctx, 0, 0, longkey, BFD_ISAAC_KEY_MAX));
	assert(ctx.rsl[0] == 0xb52429f9 && ctx.rsl[1] == 0xc6f25eb3);

	/* Nothing to seed with, or more than fits: refused, state untouched. */
	assert(!bfd_isaac_seed(&ctx, 0, 0, longkey, sizeof(longkey)));
	assert(!bfd_isaac_seed(&ctx, 0, 0, longkey, 0));
	assert(!bfd_isaac_seed(&ctx, 0, 0, NULL, 8));
	assert(ctx.rsl[0] == 0xb52429f9);
	printf("key lengths: ok\n");
}

int main(int argc, char **argv)
{
	test_reference();
	test_rfc9986();
	test_key_lengths();
	return 0;
}
